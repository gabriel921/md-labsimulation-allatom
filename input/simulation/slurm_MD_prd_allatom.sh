#! /bin/bash -e
# =============================================================================
# slurm_MD_prd_allatom.sh — Production MD SLURM submission script
#
# Reads settings from slurm_MD_prd_allatom.dat (same directory).
# Generates a .slurm job file and submits it via sbatch.
# Supports both CPU-only and GPU-accelerated GROMACS builds.
# Self-requeues until the number of segments defined in the .dat is reached.
# =============================================================================

Dir=$(pwd)

# Source the matching .dat file (same basename as this script)
runname=$(basename "$0")
source "${runname%.*}.dat"

# ── SANITY CHECK: GPU partition required for GPU build ───────────────────────
if echo "$grom" | grep -q "GPU"; then
    if ! echo "$Partition" | grep -q "GPU"; then
        echo "ERROR: GROMACS GPU build selected, but no GPU partition is set in Partition=$Partition"
        exit 1
    fi
fi

# ── GENERATE THE SLURM JOB SCRIPT ────────────────────────────────────────────
cat <<EOF > ${Name}.slurm
#! /bin/bash -e
# Auto-generated by ${runname} on $(date)

export EMAIL=${Email}
InitDate=\$(date)
export GMXLIB=\$HOME/Desktop/GMXLIB

ncpus=${ncpus}

# ── Find the next segment number ──────────────────────────────────────────────
# Segments are numbered 001, 002, ... The script checks for existing .gro files
# to determine which segment to run next.
i=1
j=001
while [ -f \${j}.gro ]; do
    i=\$((i + 1))
    j=\$(printf "%03d" \${i})
done

# On the first run (i=1), link the user-specified starting .gro as 000.gro
if [ \${i} -eq 1 ]; then
    rm -f 000.gro
    ln -s ${gro} 000.gro
fi

k=\$((i - 1))
l=\$(printf "%03d" \${k})

# ── Log job info ──────────────────────────────────────────────────────────────
{
    echo "Segment     : \${j}"
    echo "Host        : \$HOSTNAME"
    echo "CPUs        : \$ncpus"
    echo "Workdir     : /tmp/\${USER}_MD\$\$"
    echo "Started     : \$(date)"
} > \${j}.info

# ── Stage files to local scratch ─────────────────────────────────────────────
LocalScratch=/tmp/\${USER}_MD\$\$
mkdir -p \${LocalScratch}
cp -f \${l}.gro \${LocalScratch}/\${l}.gro

# Compute tinit for this segment and patch the .mdp file
tinit=\$(awk -v K=\${k} '\$1=="nsteps"{a=\$3} \$1=="dt"{b=\$3} END{print a*b*K}' ${mdp})
sed "s/tinit\s*=\s*0\.0/tinit = \${tinit}/g" ${mdp} > \${LocalScratch}/\${j}.mdp

cd \${LocalScratch}

# ── Build .tpr ───────────────────────────────────────────────────────────────
${grom} grompp \\
    -f  \${j}.mdp \\
    -po \${j}_out.mdp \\
    -c  \${l} \\
    -n  ${Dir}/${index} \\
    -p  ${Dir}/${top} \\
    -pp TMP_processed.top \\
    -o  \${j}.tpr \\
    -maxwarn 1000 >> ${Dir}/${Name}.out 2>> ${Dir}/${Name}.err

# ── Run MD ───────────────────────────────────────────────────────────────────
$(if echo "$grom" | grep -q "GPU"; then
cat <<GPUBLOCK
# GPU run: single MPI rank, all threads as OpenMP
GPUid=0
if [ "$(nvidia-smi -L | wc -l)" -gt 1 ]; then
    # If another gmx mdrun is using a GPU, pick the other one (0→1 or 1→0)
    OtherGPU=$(ps -aux | awk '{for(i=1;i<=NF;i++) if($i=="-gpu_id") print $(i+1)}')
    if [ -n "\$OtherGPU" ]; then
        GPUid=$((1 - OtherGPU))
    fi
fi

${grom} mdrun \\
    -ntmpi  1 \\
    -ntomp  ${ncpus} \\
    -pin    auto \\
    -gpu_id \${GPUid} \\
    -s      \${j}.tpr \\
    -x      \${j}.xtc \\
    -c      \${j}.gro \\
    -e      \${j}.edr \\
    -g      \${j}.log \\
    -rcon   ${Rcon} \\
    -nice   19 >> ${Dir}/${Name}.out 2>> ${Dir}/${Name}.err
GPUBLOCK
else
cat <<CPUBLOCK
# CPU-only run
${grom} mdrun \\
    -nt     ${ncpus} \\
    -pin    auto \\
    -s      \${j}.tpr \\
    -x      \${j}.xtc \\
    -c      \${j}.gro \\
    -e      \${j}.edr \\
    -g      \${j}.log \\
    -rcon   ${Rcon} \\
    -nice   19 >> ${Dir}/${Name}.out 2>> ${Dir}/${Name}.err
CPUBLOCK
fi)

# ── Copy outputs back and verify ─────────────────────────────────────────────
cp -df \${j}*.{tpr,gro,xtc,edr,log} ${Dir}/

# Copy pull/umbrella-sampling files if present
if [ -f pullx.xvg ]; then
    for pull in x f; do
        cp -f pull\${pull}.xvg ${Dir}/\${j}_pull\${pull}.xvg
    done
fi

# Verify copy succeeded.
# NOTE: this loop must check EVERY file, not just report the exit status of
# the last diff run. A bare "for f in ...; do diff ...; done" only carries
# the exit status of its FINAL iteration — if an earlier file (e.g. the
# .xtc) fails to copy but a later one (e.g. .log) succeeds, the loop as a
# whole reports success and the failure is silently swallowed. That
# previously let a corrupted/missing .xtc slip past verification and then
# get wiped out by "rm -rf \${LocalScratch}" below, with no recovery copy
# left anywhere. Track failures explicitly across all files instead.
verify_failed=0
for f in \${j}*.{tpr,gro,xtc,edr,log}; do
    if ! diff -q "\$f" "${Dir}/\$f" > /dev/null 2>&1; then
        echo "  MISMATCH/MISSING: \$f" >> \${j}.info
        verify_failed=1
    fi
done

if [ "\${verify_failed}" -eq 1 ]; then
    echo "ERROR: file copy verification failed — local files kept in \${LocalScratch} for recovery (NOT deleted)." >> \${j}.info
    exit 1
fi

# Compress and clean up (only reached if every file verified OK above)
cd ${Dir}
rm -rf \${LocalScratch}

echo "Finished : \$(date)" >> \${j}.info

# ── Email notification ───────────────────────────────────────────────────────
if [ -n "\${EMAIL}" ]; then
    echo -e "Segment \${j} of job ${Name} finished on \$HOSTNAME\\n  Started : \$InitDate\\n  Ended   : \$(date)" \\
        | mutt -s "Cluster Report: ${Name} segment \${j}" "\${EMAIL}"
fi

# ── Self-requeue for next segment ────────────────────────────────────────────
if [ \${i} -lt ${Segments} ]; then
    ./${runname}
fi

exit 0
EOF

# ── SUBMIT ───────────────────────────────────────────────────────────────────
chmod +x ${Name}.slurm

if [ "${requeue}" -eq 1 ]; then
    sbatch --requeue -p ${Partition} -N 1 -n ${ncpus} \
        -o ${Name}.sout -e ${Name}.serr ${Name}.slurm
else
    sbatch -p ${Partition} -N 1 -n ${ncpus} \
        -o ${Name}.sout -e ${Name}.serr ${Name}.slurm
fi

echo ""
echo "Job '${Name}' submitted to partition(s): ${Partition} with ${ncpus} threads"
echo "Segments to run: ${Segments}"
